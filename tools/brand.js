function swiftPath(d){ const p=svgpath(d).abs().unarc().unshort(); const L=[];
  p.iterate((s,_,x,y)=>{const c=s[0];
   if(c==='M')L.push(`p.move(to: P(${f(s[1])}, ${f(s[2])}))`); else if(c==='L')L.push(`p.addLine(to: P(${f(s[1])}, ${f(s[2])}))`);
   else if(c==='H')L.push(`p.addLine(to: P(${f(s[1])}, ${f(y)}))`); else if(c==='V')L.push(`p.addLine(to: P(${f(x)}, ${f(s[1])}))`);
   else if(c==='C')L.push(`p.addCurve(to: P(${f(s[5])}, ${f(s[6])}), control1: P(${f(s[1])}, ${f(s[2])}), control2: P(${f(s[3])}, ${f(s[4])}))`);
   else if(c==='Q')L.push(`p.addQuadCurve(to: P(${f(s[3])}, ${f(s[4])}), control: P(${f(s[1])}, ${f(s[2])}))`);
   else if(c==='Z')L.push('p.closeSubpath()'); else throw new Error(c);}); return L.join('\n        '); }
